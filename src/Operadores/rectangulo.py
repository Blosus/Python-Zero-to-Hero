print(f'*** Calculo area y perimetro ***')

base = float(input("Brindame la base de la figura: "))
altura = float(input('Brindame la altura de la figura: '))

area = base * altura
perimetro = 2 * (base + altura)

print(f'El area del rectangulo es: {area}')
print(f'El perimetro del rectangulo es: {perimetro}')