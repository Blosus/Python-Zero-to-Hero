print('*** Operadores Comparacion (Relacionales) ***')
a, b = 7, 5
print(f'Valor inicial a: {a}, b: {b}')

# Operadores igualdad ==
resultado = a == b #false
print(f'Resultado a == b es: {resultado}')

# Operador diferente !=
resultado = a != b
print(f'Resultado a != b es: {resultado}')

# Operador mayor que >
resultado = a > b
print(f'Resultado a > b es: {resultado}')

# Operador mayor o igual que >=
resultado = a >= b
print(f'Resultado a >= b es: {resultado}')

# Operador menor que
resultado = a < b
print(f'Resultado a < b es: {resultado}')

# Operador menor igual que
resultado = a <= b
print(f'Resultado a <=b b es: {resultado}')